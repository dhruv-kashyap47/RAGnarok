import json

import httpx
from fastapi import HTTPException

from app.core.config import (
    CHAT_TIMEOUT_SECONDS,
    GROQ_API_BASE,
    GROQ_API_KEY,
    GROQ_CHAT_MODEL,
)
from app.core.logger import logger

# Created lazily so it binds to the running event loop and can be cycled on
# shutdown (e.g. across test lifespans).
_client: httpx.AsyncClient | None = None


def _get_client() -> httpx.AsyncClient:
    global _client
    if _client is None or _client.is_closed:
        _client = httpx.AsyncClient(timeout=CHAT_TIMEOUT_SECONDS)
    return _client


async def close_http_client() -> None:
    """Close the shared HTTP client on application shutdown."""
    global _client
    if _client is not None and not _client.is_closed:
        await _client.aclose()
    _client = None


def get_llm_provider() -> str:
    """Groq is the only supported provider."""
    return "groq" if GROQ_API_KEY else "unconfigured"


def get_llm_model() -> str:
    return GROQ_CHAT_MODEL


def _extract_error(response: httpx.Response) -> str:
    try:
        payload = response.json()
    except ValueError:
        return response.text or "LLM request failed"
    error = payload.get("error") or {}
    return error.get("message") or response.text or "LLM request failed"


def _require_api_key() -> None:
    if not GROQ_API_KEY:
        raise HTTPException(status_code=500, detail="GROQ_API_KEY is not configured")


async def generate_answer(prompt: str) -> str:
    if not prompt or not prompt.strip():
        raise HTTPException(status_code=400, detail="Prompt cannot be empty.")
    _require_api_key()

    logger.info("Sending prompt to Groq model=%s", GROQ_CHAT_MODEL)
    try:
        response = await _get_client().post(
            f"{GROQ_API_BASE}/chat/completions",
            headers={"Authorization": f"Bearer {GROQ_API_KEY}"},
            json={
                "model": GROQ_CHAT_MODEL,
                "messages": [{"role": "user", "content": prompt}],
                "temperature": 0.3,
                "max_tokens": 1024,
            },
        )
    except httpx.HTTPError as exc:
        logger.error("Groq transport error: %s", exc)
        raise HTTPException(
            status_code=502,
            detail="Groq generation request failed. Please try again later.",
        ) from exc

    if response.status_code >= 400:
        logger.error("Groq failed status=%s", response.status_code)
        raise HTTPException(
            status_code=502,
            detail=f"Groq generation failed: {_extract_error(response)}",
        )

    data = response.json()
    text = data.get("choices", [{}])[0].get("message", {}).get("content", "").strip()
    logger.info("Groq generation completed")
    return text


async def stream_generate_answer(prompt: str):
    """Yield chunks of text generated by the LLM (Groq SSE stream)."""
    if not prompt or not prompt.strip():
        raise HTTPException(status_code=400, detail="Prompt cannot be empty.")
    _require_api_key()

    logger.info("Streaming prompt to Groq model=%s", GROQ_CHAT_MODEL)
    try:
        async with _get_client().stream(
            "POST",
            f"{GROQ_API_BASE}/chat/completions",
            headers={"Authorization": f"Bearer {GROQ_API_KEY}"},
            json={
                "model": GROQ_CHAT_MODEL,
                "messages": [{"role": "user", "content": prompt}],
                "temperature": 0.3,
                "max_tokens": 1024,
                "stream": True,
            },
        ) as response:
            if response.status_code >= 400:
                body = await response.aread()
                logger.error("Groq failed status=%s body=%s", response.status_code, body)
                raise HTTPException(
                    status_code=502,
                    detail=f"Groq generation failed: {_extract_error(response)}",
                )

            async for line in response.aiter_lines():
                if line.startswith("data: "):
                    data_str = line[6:]
                    if data_str.strip() == "[DONE]":
                        break
                    try:
                        data = json.loads(data_str)
                        text_chunk = data.get("choices", [{}])[0].get("delta", {}).get("content", "")
                        if text_chunk:
                            yield text_chunk
                    except (json.JSONDecodeError, IndexError, TypeError, AttributeError, KeyError):
                        # Malformed SSE frame (keepalive, truncated JSON):
                        # skip it and keep streaming.
                        logger.debug("Skipping malformed Groq stream frame")
    except httpx.HTTPError as exc:
        logger.error("Groq stream transport error: %s", exc)
        raise HTTPException(
            status_code=502,
            detail="Groq generation request failed. Please try again later.",
        ) from exc
